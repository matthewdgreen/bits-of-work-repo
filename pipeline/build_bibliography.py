def build_page(entries, generated):
    by_year = {}
    for f in entries:
        by_year.setdefault(f.get('countyear', 'n.d.'), []).append(f)
    years = sorted(by_year, key=lambda y: (y == 'n.d.', -int(y) if y.isdigit() else 0))
    total = {k: 0.0 for k, *_ in CLASSES}
    for f in entries:
        for part in f.get('classes', '').split(', '):
            if part:
                label, w = part.rsplit(' ', 1)
                total[KEY_OF[label]] += float(w)

    def sums(fs):
        s = {k: 0.0 for k, *_ in CLASSES}
        for f in fs:
            for part in f.get('classes', '').split(', '):
                if part:
                    label, w = part.rsplit(' ', 1)
                    s[KEY_OF[label]] += float(w)
        return ''.join(f'<span class="cls"><i style="background:var(--s-{k})"></i>{LABEL[k]} {v:.4g}</span>'
                       for k, v in s.items() if v)

    index = []
    for y in years:
        index.append(f'<a href="#y{y}" data-y="{y}">{y}<span>{len(by_year[y])}</span></a>')
    sections = []
    for y in years:
        fs = sorted(by_year[y], key=sort_key)
        dl = f'<a class="dl" href="bib/{y}.bib" download>{y}.bib</a>' if y.isdigit() else ''
        sections.append(
            f'<section class="yr" id="y{y}" data-y="{y}"><h2><span class="n">{y}</span>'
            f'<span class="cnt">{len(fs)} item{"s" if len(fs) != 1 else ""}</span>{dl}</h2>'
            f'<div class="sums">{sums(fs)}</div><ol class="bib">'
            + ''.join(render_entry(f) for f in fs) + '</ol></section>')
