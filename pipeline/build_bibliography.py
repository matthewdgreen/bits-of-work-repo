#!/usr/bin/env python3
"""Build the counted-paper bibliography: BibTeX first, then a web page rendered from it.

Run from the repo root:  python3 -I pipeline/build_bibliography.py

Input: data/export/combined_included.csv, restricted to the rows the paper counts use
(include = yes, effort categories A-F and H; see analysis/phase1_counts.py).
Outputs:
  docs/bibliography.bib     every counted item, newest first
  docs/bib/<year>.bib       the same entries split by year
  docs/bibliography.html    a readable page generated by parsing docs/bibliography.bib
Custom BibTeX fields: classes (fractional class weights used in the counts, after version
weights), category, rationale (the classifier's one-line reason), vetted, peerreviewed,
sources, studyid, countyear, version (when the item is a duplicate version or extension).

Optional sidecars, joined on `id` when present (written by the venue-resolution work):
  data/venues/published_venues.csv  id, pub_venue, pub_type, pub_year, pub_doi, confidence, evidence, ...
      A row with a pub_venue and confidence >= MIN_CONFIDENCE replaces the entry's venue and type
      (journal -> @article, conference -> @inproceedings, thesis -> @phdthesis, book -> @book,
      chapter -> @incollection) and sets the citation `year` to pub_year. ePrint fields are kept,
      and ePrint items take only a real publication (not a preprint/report/other listing).
  data/venues/corrections.csv       id, field, value, evidence
      Corrects title, authors or venue only.
Neither sidecar can change what is counted: page grouping and `countyear` always use the
counting year from the export, and class weights come only from the export.
Stdlib only.
"""
from pathlib import Path
from html import escape
import csv, json, re, unicodedata, datetime

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / 'docs'
EFFORT = set('ABCDEFH')
CLASSES = [  # site key, label, export weight columns (lattices = MLWE + plain LWE)
    ('lattice', 'Lattices', ['w_MLWE_structured', 'w_LWE_plain']),
    ('ecdlp', 'ECDLP', ['w_ECDLP']),
    ('code', 'Syndrome decoding', ['w_SD_code']),
    ('factoring', 'Factoring/FF-DLP', ['w_Factoring_FFDLP']),
    ('isogeny', 'Isogenies', ['w_Isogeny']),
    ('mq', 'Multivariate', ['w_Multivariate']),
]
LABEL = {k: l for k, l, _ in CLASSES}
KEY_OF = {l: k for k, l, _ in CLASSES}
CATEGORY = {
    'A': 'classical algorithm', 'C': 'structural result', 'D': 'cost model or security estimate',
    'E': 'computational record', 'F': 'lower bound or generic-model result',
    'H': 'retracted claim or refutation', 'B': 'quantum algorithm', 'G': 'hardness theory', 'S': 'survey',
}
EPRINT = re.compile(r'^\d{4}/\d+$')
MIN_CONFIDENCE = 0.7
PUB_TYPE = {'journal': ('article', 'journal'), 'conference': ('inproceedings', 'booktitle'),
            'thesis': ('phdthesis', 'school'), 'book': ('book', 'publisher'),
            'chapter': ('incollection', 'booktitle')}
CORRECTABLE = {'title', 'authors', 'venue'}


PEER_REFEREED = {'yes', 'likely'}
PEER_KINDS = {'journal', 'conference', 'workshop'}


def load_sidecars():
    """Published-venue resolutions, metadata corrections and peer-review flags keyed by export id."""
    pubs, fixes, peer = {}, {}, set()
    pv = ROOT / 'data/venues/published_venues.csv'
    if pv.exists():
        for r in csv.DictReader(pv.open()):
            if r.get('refereed') in PEER_REFEREED and r.get('venue_kind') in PEER_KINDS:
                peer.add(r['id'])
            try:
                conf = float(r.get('confidence') or 1)
            except ValueError:
                conf = 0
            if not r.get('pub_venue', '').strip() or conf < MIN_CONFIDENCE:
                continue
            if EPRINT.match(r['id']) and r.get('pub_type') not in PUB_TYPE:
                continue          # ePrint's own listing is already cited more precisely
            pubs[r['id']] = r
    cf = ROOT / 'data/venues/corrections.csv'
    if cf.exists():
        for r in csv.DictReader(cf.open()):
            if r.get('field') in CORRECTABLE:
                fixes.setdefault(r['id'], {})[r['field']] = r['value']
    return pubs, fixes, peer


# ---------------------------------------------------------------- BibTeX writing
def tex_escape(s):
    """Escape BibTeX/LaTeX specials outside $...$ math; keep math as written."""
    s = re.sub(r'\s+', ' ', s).strip()
    parts = re.split(r'(\$[^$]*\$)', s)
    out = []
    for p in parts:
        if p.startswith('$') and p.endswith('$') and len(p) > 1:
            out.append(p)
            continue
        p = p.replace('\\', '\\textbackslash{}') if '$' not in s else p
        for a, b in (('&', r'\&'), ('%', r'\%'), ('#', r'\#'), ('_', r'\_'),
                     ('^', r'\^{}'), ('~', r'\textasciitilde{}')):
            p = p.replace(a, b)
        out.append(p)
    s = ''.join(out)
    # BibTeX needs balanced braces
    depth = 0
    for ch in s:
        depth += (ch == '{') - (ch == '}')
        if depth < 0:
            break
    if depth != 0:
        s = s.replace('{', '').replace('}', '')
    return s


def cite_key(row):
    i = row['id']
    if EPRINT.match(i):
        return 'eprint:' + i.replace('/', '-')
    if i.startswith('dblp:'):
        return 'dblp:' + re.sub(r'[^A-Za-z0-9/._-]', '', i[5:]).replace('/', '-')
    if i.startswith('zb:'):
        return 'zbmath:' + i[3:]
    return 'openalex:' + i


def entry(row, pub=None, peer=False, keys=None):
    i, venue = row['id'], row['venue'].strip()
    f = {}
    # dblp disambiguates homonyms with a numeric suffix ("Thomas Johansson 0001"); drop it
    authors = [re.sub(r'\s+\d{4}$', '', re.sub(r'\s+', ' ', a).strip()) for a in row['authors'].split(';') if a.strip()]
    if authors:
        f['author'] = ' and '.join(tex_escape(a) for a in authors)
    f['title'] = '{' + tex_escape(row['title']) + '}'
    if EPRINT.match(i):
        typ = 'misc'
        f['howpublished'] = f'Cryptology {{ePrint}} Archive, Paper {i}'
        f['eprint'], f['eprinttype'] = i, 'iacr'
        if venue:
            f['eprintclass'] = tex_escape(venue)
        url = f'https://eprint.iacr.org/{i}'
    elif i.startswith('dblp:journals/') and venue:
        typ, f['journal'] = 'article', tex_escape(venue)
        url = f'https://dblp.org/rec/{i[5:]}'
    elif i.startswith('dblp:conf/') and venue:
        typ, f['booktitle'] = 'inproceedings', tex_escape(venue)
        url = f'https://dblp.org/rec/{i[5:]}'
    elif i.startswith('dblp:phd/'):
        typ = 'phdthesis'
        f['school'] = tex_escape(venue) if venue else 'unknown'
        url = f'https://dblp.org/rec/{i[5:]}'
    else:
        typ = 'misc'
        if venue:
            f['howpublished'] = tex_escape(venue)
        url = (f'https://zbmath.org/?q=an:{i[3:]}' if i.startswith('zb:')
               else f'https://dblp.org/rec/{i[5:]}' if i.startswith('dblp:')
               else f'https://openalex.org/{i}')
    if pub and pub.get('pub_type') in PUB_TYPE:
        # published version found: cite it, keep the ePrint pointers alongside
        for k in ('journal', 'booktitle', 'howpublished', 'school'):
            f.pop(k, None)
        typ, field = PUB_TYPE[pub['pub_type']]
        f[field] = tex_escape(pub['pub_venue'])
        if EPRINT.match(i):
            f['note'] = f'Also Cryptology {{ePrint}} Archive, Paper {i}'
    elif pub:
        f['howpublished'] = tex_escape(pub['pub_venue'])
    year = (pub or {}).get('pub_year', '').strip() or row['year']
    if year:
        f['year'] = year
    doi = row['doi'] or (pub or {}).get('pub_doi', '').strip()
    if doi:
        f['doi'] = doi
        row = dict(row, doi=doi)
    f['url'] = f'https://doi.org/{row["doi"]}' if row['doi'] and not EPRINT.match(i) else url
    weights = []
    for k, label, cols in CLASSES:
        w = sum(float(row[c] or 0) for c in cols)
        if w > 0:
            weights.append(f'{label} {w:g}')
    f['classes'] = ', '.join(weights)
    f['category'] = row['category']
    f['rationale'] = tex_escape(row['reason'])
    f['vetted'] = 'yes' if row['vetted'] == 'True' else 'no'
    f['peerreviewed'] = 'yes' if peer else 'no'
    f['quantum'] = 'yes' if row.get('quantum') == 'True' else 'no'
    vw, vof = row.get('version_weight', '1'), row.get('version_of', '')
    if vof and keys:
        if float(vw) == 0:
            f['version'] = f'same work as {keys.get(vof, vof)}; counted there, weight 0 here'
        else:
            f['version'] = f'journal extension of {keys.get(vof, vof)}; counted at {float(vw):.2g}'
    f['sources'] = row['sources'].replace('|', ', ')
    f['studyid'] = i
    f['countyear'] = row['year'] or 'n.d.'
    if pub:
        f['venuenote'] = tex_escape(f"published venue resolved from {pub.get('evidence') or 'external metadata'}"
                                    + (f" (confidence {pub['confidence']})" if pub.get('confidence') else ''))
    body = ',\n'.join(f'  {k:<12} = {{{v}}}' for k, v in f.items())
    return f'@{typ}{{{cite_key(row)},\n{body}\n}}\n'


# ---------------------------------------------------------------- BibTeX reading
ENTRY = re.compile(r'@(\w+)\{([^,]+),\n(.*?)\n\}\n', re.S)
FIELD = re.compile(r'^  (\w+)\s*= \{(.*)\},?$')


def parse_bib(text):
    out = []
    for typ, key, body in ENTRY.findall(text):
        f = {'_type': typ, '_key': key}
        for line in body.splitlines():
            m = FIELD.match(line)
            if m:
                f[m[1]] = m[2]
        out.append(f)
    return out


def detex(s):
    """BibTeX text -> HTML, with $...$ turned into KaTeX inline delimiters."""
    parts = re.split(r'(\$[^$]*\$)', s)
    out = []
    for p in parts:
        if p.startswith('$') and p.endswith('$') and len(p) > 1:
            out.append(escape('\\(' + p[1:-1] + '\\)'))
            continue
        for a, b in ((r'\&', '&'), (r'\%', '%'), (r'\#', '#'), (r'\_', '_'), (r'\^{}', '^'),
                     (r'\textasciitilde{}', '~'), (r'\textbackslash{}', '\\')):
            p = p.replace(a, b)
        out.append(escape(p.replace('{', '').replace('}', '')))
    return ''.join(out)


def version_note(f):
    v = f['version']
    m = re.match(r'(same work as|journal extension of) (\S+); (.*)', v)
    if not m:
        return f'<div class="ver">{escape(v)}</div>'
    what, key, rest = m.groups()
    return (f'<div class="ver">{"Same work as" if what.startswith("same") else "Journal extension of"} '
            f'<a href="#{escape(key)}">{escape(key)}</a>; {escape(rest)}.</div>')


def short_name(full):
    parts = full.split()
    if len(parts) < 2:
        return full
    initials = ' '.join(p[0] + '.' for p in parts[:-1] if p[0].isalpha())
    return f'{initials} {parts[-1]}'


def sort_key(f):
    first = f.get('author', '').split(' and ')[0].split()
    last = first[-1] if first else '~'
    return (unicodedata.normalize('NFKD', last).lower(), f.get('title', ''))


def render_entry(f):
    authors = [a for a in f.get('author', '').split(' and ') if a]
    names = ', '.join(escape(short_name(detex(a))) for a in authors[:6])
    if len(authors) > 6:
        names += ' et al.'
    venue = f.get('journal') or f.get('booktitle') or f.get('howpublished') or f.get('school') or ''
    classes = []
    for part in f.get('classes', '').split(', '):
        if not part:
            continue
        label, w = part.rsplit(' ', 1)
        k = KEY_OF.get(label, 'lattice')
        frac = '' if float(w) == 1 else f' <span class="w">{float(w):.2g}</span>'
        classes.append(f'<span class="cls" data-c="{k}"><i style="background:var(--s-{k})"></i>{escape(label)}{frac}</span>')
    cat = f.get('category', '')
    links = [f'<a href="{escape(f["url"])}">{"ePrint" if f.get("eprinttype") == "iacr" else "link"}</a>']
    if f.get('doi') and f.get('eprinttype') == 'iacr':
        links.append(f'<a href="https://doi.org/{escape(f["doi"])}">doi</a>')
    links.append(f'<button class="bibbtn" data-key="{escape(f["_key"])}">BibTeX</button>')
    ckeys = ' '.join(KEY_OF.get(p.rsplit(" ", 1)[0], '') for p in f.get('classes', '').split(', ') if p)
    end = lambda t: t if re.search(r'[.?!]\s*(</span>)?$', t) else t + '.'
    return (
        f'<li id="{escape(f["_key"])}" data-c="{ckeys}" data-v="{f.get("vetted", "no")}" data-p="{f.get("peerreviewed", "no")}" data-q="{f.get("quantum", "no")}"'
        + (' class="dup"' if f.get('version', '').startswith('same work') else '') + '>'
        f'<span class="au">{end(names)}</span> <span class="ti">{end(detex(f.get("title", "")))}</span> '
        + (f'<span class="ve">{detex(venue)}</span>, ' if venue else '')
        + f'{escape(f.get("year", "n.d."))}.'
        f'<div class="meta">{"".join(classes)}'
        f'<span class="cat" title="{escape(CATEGORY.get(cat, ""))}">{escape(cat)} · {escape(CATEGORY.get(cat, ""))}</span>'
        + (f'<span class="cy" title="Counts use the year the work first appeared">counted in {escape(f["countyear"])}</span>'
           if f.get('countyear') and f.get('year') and f['year'] != f['countyear'] else '')
        + ('<span class="qu" title="Quantum algorithms or quantum resource estimates are the main point">quantum</span>'
           if f.get('quantum') == 'yes' else '')
        + f'<span class="links">{" ".join(links)}</span></div>'
        f'<div class="why">{detex(f.get("rationale", ""))}</div>'
        + (version_note(f) if f.get('version') else '') + '</li>'
    )


